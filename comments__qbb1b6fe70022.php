<B>Viện Việt Học tổ chức tưởng niệm Giáo Sư Viện Trưởng Nguyễn Đình Hòa</B> 

GARDEN GROVE (AT). Viện Việt Học tại Hoa Kỳ đã tổ chức một buỗi lễ cầu siêu và tưởng niệm trang trọng và cảm động cố giáo sư Viện Trưởng Nguyễn Đình Hòa với sự tham dự của khá đông học giả, giáo sư, môn đệ và gia đình tại chùa Liên Hoa vào chiều ngày Chủ Nhật Mồng 3 tháng Sáu 2001.

Giáo sư Nguyễn Khắc Hoạch đã nhắc đến những công trình văn học giá trị, những khám phá về ngôn ngữ độc đáo mà giáo sư Nguyễn Đình Hòa đã đóng góp cho kho tàng văn hóa Việt Nam. Giáo sư Nguyện Đình Hòa đã tốt nghiệp luật khoa tại Hà Nội năm 1945, du học tại Hoa kỳ với học vị Tiến Sĩ Giáo Dục vào năm 1956 tại New York University và về Ngôn Ngữ Học tại Georgetown University, Linguistic Institute, Washington DC: Summer'54.

Giáo Sư đã từng làm Khoa trưởng Đại Học văn Khoa ở Việt Nam, dạy học tại nhiều Đại Học Hoa Kỳ. Trong suốt cuộc đời giảng dậy và nghiên cứu, giáo sư Nguyễn Đình Hòa đã để lại một số lượng tác phẩm vô cùng phong phú về các công trình nghiên cứu ngôn ngữ, văn hóa Việt Nam và phát triễn Việt Học.

Sau khi nghỉ hưu được ít lâu, giáo sư Nguyễn Đình Hòa đã cùng với một số giáo sư Đại Học và các bạn trẻ thành lập Viện Việt-Học vào năm 1999 với mục đích phát huy nền văn hóa Việt Nam đến với giới trẻ trí thức hải ngoại. Giáo sư Nguyễn Đình Hòa đã mất tại miền Bắc California vào ngày 10 tháng 12 năm 2000 sau một cuộc giải phẫu tim và bị hôn mê suốt hơn 2 tháng trời trước khi trút hơi thở cuối cùng. Sự ra đi của giáo sư là cái tang to lớn trong nền văn hóa và giáo dục và cũng là sự thiệt thòi cho giới trẻ Việt nam tại hải ngoại.

Sau lễ tưởng niệm và cầu siêu do Họa Thượng Chơn Thành Viện chủ chùa Liên Hoa chủ trì, giáo sư Nguyễn Đình Cường, đại diện gia đình đã cảm tạ sự hiện diện đông đảo của quan khách và thân hữu cũng như môn đệ của cố giáo sư Nguyễn Đình Hòa. Trong dịp này, Viện Việt-Học đã ấn hành một đặc san Tưởng Niệm Cố Giáo Sư Viện Trưởng Nguyễn Đình Hòa với đầy đủ tiểu sử, sự nghiệp và những ngày cuối cùng của cố Giáo Sư Nguyễn Đình Hòa.

