<br />      Giá-trị một bài khảo-cứu nằm trong các điều tìm tòi được một cách nghiêm-chỉnh, hoặc mới mẻ, hoặc khơi mào được tranh-luận, cốt mời độc-giả tham-gia thảo-luận, phê-bình chỉ-trích.
<br />    
<br />      Các quan-điểm nêu lên trong bài tôi viết quan-trọng hơn là lời văn, dù nhẹ-nhàng, bác-học hay sát-phạt. Độc-giả không bằng lòng với lời văn, vẫn cần tìm hiểu các quan-điển tôi nêu ra, nhất là các khiá cạnh khác như lịch-sử, Trung-quốc triết-học-sử, Trung-quốc Ngữ-ngôn-học-sử hay hàng loạt các danh-tác về Cổ-âm-vận-học hậu-bán thế-kỷ thứ 20 hay ít nhất cũng là những điều tôi chứng-kiến cùng lúc với các nhân-sĩ lão-thành đương-thời.
<br />     
<br />       Trong bài Lược-sử Kinh Dịch tại VN tôi chỉ căn-cứ vào các tài-liệu và sử-liệu viết bằng Giáp-cốt-văn, Hán-văn, chữ Nôm và chữ Quốc-ngữ để tường-thuật quá-trình truyền-bá Kinh Dịch tại VN và phê-bình ngắn ngủi là trong các bộ Kinh Dịch viết bằng chữ QN mà tôi đã từng đọc trong mấy chục năm qua, chỉ có quyển Chu Dịch Bản-nghiã của Cụ Cử Nguyễn-duy-Tinh là dịch tương-đối ít sai nhất về âm-nghiã . Rút bỏ bài cuả tôi để thế bằng một bài khác hẳn là tước bỏ quyền đối-thoại giữa tôi và các độc-giả về đề-tài tôi nêu lên trong bài. Chính nhờ tranh-luận hai bên mới học hỏi thêm và mới biết đâu là trúng trật. 
<br />     
<br />      Một Viện nghiêm-chỉnh như VVH không nên tước đoạt quyền học, hỏi, hiểu, hành cuả tác-giả và độc-giả. Vả chăng, đa đa ích thiện, càng nhiều bài đóng góp về một đề-tài nào đó, đề-tài ấy lại càng phong-phú thêm.
<br />       
<br />      Trước năm 1975, văn-hoá Miền Bắc không được phong-phú, đa-diện như văn-hoá Miền Nam, chỉ vì người dân Miền Bắc bị mất quyền tự-do học hỏi, bàn luận, tự-do suy nghĩ và phổ-biến tư-tưởng cuả mình. Tóm lại mất hết quyền nhìn xa, biết rộng.
<br />    
<br />      Tôi cảm thương cho VVH đã rộng mở cửa cho độc-giả toàn-cầu mà vẫn còn áp-dụng chính-sách cai-trị độc-tài cuả chính-quyền CS: cá nhân khỏi cần suy nghĩ, quyền suy nghĩ, định đoạt nằm hết trong tay một thiểu-số cầm quyền.
<br />
<br />      Tiện đây tôi xin lệ-cử vài nhận-xét về bài Không-gian Kinh Dịch (KGKD) cuả GS LeVanDang để minh-hoạ đối-thoại giữa tác-giả và độc-giả:
<br />      1) Trong Dịch, Âm-dương cộng tồn (Coexistence), khi muốn biểu-thị quẻ đơn hay quẻ kép, không thể dùng một số nguyên thiên-nhiên (whole number) mà phải dùng một số nguyên đại-số (integer), tức là một số nguyên dương (+) hay âm (-). Muốn hiểu rõ vấn-đề này xin đọc bài tôi viết trong Khai-thác Thị-trường số 7 (July/August/September 1992), tr. 60-64. Lý do là có quẻ âm phải có quẻ dương, có Nam thì có Nữ v.v. vì Cô dương bất sinh, độc âm bất thành.
<br />      2) Trong tất cả các bộ Chu Dịch cuả các danh-sĩ viết bằng văn-ngôn hay bạch-thoại từ Tần-Hán đến giờ, ở Đại-lục cũng như ở Đài-Loan, không sách danh tiếng nào gọi quẻ kép (tức trùng-quái hay biệt-quái) là tạp-quái cả, vì tạp-quái chỉ dùng riêng cho 62 quẻ con do hai quẻ cha mẹ Kiền Khôn sinh ra.
