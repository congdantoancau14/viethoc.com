Bốn câu khởi này thường dùng để giới thiệu cũng như giải thích sự biến hoá của Kinh Dịch. Tuy nhiên, đối với phần đông giới trẻ hoặc người khoa học tánh, bốn câu ấy không đủ để thuyết phục hoặc làm tăng tánh hiếu kỳ ngõ hầu tạo cơ hội tìm hiểu thêm về môn Kinh Dịch.

Giáo Sư Lê Văn Ðặng vừa gởi đến Viện Việt-Học, và xin được giới thiệu cùng quý độc giả bài khảo luận <a href="/eholdings/ICkhgian.pdf">Không Gian Chu Dịch</a>. Không gian  Descartes 1, 2, 3 chiều trong Toán Học được áp dụng vào <i><b>"Không Gian Chu Dịch"</b></i>, các quẻ Dịch đơn và kép được biểu thị bằng số nhị phân, và các đồ biểu cổ điển của các quẻ dịch đều được điện tử hoá, có thể đưa vào máy điện toán qua bàn chữ như các mẫu tự a, b, c,...

Trong bài khảo luận này GS. Lê Văn Ðặng giải thích cặn kẽ sự biến hoá của Chu Dịch. Thêm vào ấy, GS. giới thiệu một số ký hiệu tương đương với chữ Hán của các quẻ cho dễ hiểu. Một khía cạnh khác trong bài khảo luận này của GS là có phụ thêm chữ Hán cho tiện bề tham luận. 

