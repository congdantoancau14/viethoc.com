		<td class="type5" background="" valign="top">
	<a href="search.php?query=&amp;topic=3&amp;author="><img src="./images/topics/vcvn_WEB.jpg" border="0" alt="Văn-chương Việt-Nam" align="right" hspace="4" /></a>Trong <b>Dự án Chinh Phụ Ngâm</b>, chúng tôi khảo lục <br>
<br /><ul>
<br /><li>Nguyên tác chữ Hán của Ðặng Trần Côn, </li>
<br /><li>bản Diễn Âm của Ðoàn Thị Ðiểm, các bản dịch ra </li><ul>
<br /><li>chữ Nhật (Takeuchi), </li>
<br /><li>chữ Anh (Huỳnh Sanh Thông), </li>
<br /><li>chữ Pháp (Huỳnh Khắc Dụng).  </li>
<br /></ul>
<br /></ul> <br />Các bản chữ Nhật và chữ Anh đã được chuyển nhập xong, sau bản chữ Hán và phiên âm chữ Việt.  Riêng bản chữ Pháp, chúng tôi chỉ có một bản do cơ sở Ðông Tiến phát hành vào tháng 7 năm 1988.  Bản này lại có mấy chỗ tồn nghi nên chúng tôi chưa vội phổ biến.  Chúng tôi đã làm thủ tục xin phép dịch giả (bản chữ Anh) hoặc người thừa hưởng tác quyền (bản chữ Nhật) nhưng chưa được hồi đáp.<br>
<br />Hiện thời, bản chữ Hán đã hoàn tất.  Kính mời quý vị vào <a href="https://www.viethoc.org/content.php?menu=24&page_id=47" target="new_window">Việt-Học Thư Quán</a> đọc <a href="https://www.viethoc.org/eholdings/CPN-HAN-QN-Ming_D7A.pdf" target="new_window">Chinh Phụ Ngâm Khúc</a> của Ðặng Trần Côn.  Chúng tôi phổ biến <b>Dự án Chinh Phụ Ngâm</b> với sự dè dặt thường lệ, dám mong quý vị chỉ cho chỗ sai sót.  Ða tạ.<br>
<br />Thân kính,<br>
<br />Viện Việt-Học
