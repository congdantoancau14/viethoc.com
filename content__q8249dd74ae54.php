               <td class="type5" width="90%" valign="top"><span class="boldtext">Prof. Nguyen, Khac-Hoach</span><br /><p>Professor Nguyen Khac Hoach was born 15 May 1921 in Vietnam. He earned the Licence es Lettres in Paris in 1950, the Doctorat es Lettres (Doctorat d'Etat) at La Sorborne (Paris 1955), the Diplome de l'Institut des Hautes Etudes Internationales de la Faculte de Droit (Paris 1952), and the Diplome du Centre d'Etudes Europeennes, University of Nancy (1957). Currently involved in poetic writing and in research on comparative literature. Professor Nguyen has taught French, Vietnamese, and comparative literature at the University of Saigon since 1957. He has also been Dean of the Faculty of Letters of Saigon (1965-1969), a visiting professor of French and Vietnamese literature at Southern Illinois University (Carbondale, Illinois, U.S.A.) from 1970 to 1974, and editor of XXth Century, a literary review (1960). Professionally affiliated with the Modern Languages Association (since 1971), the Association of American University Professors (since 1973), the Association for Asian Studies (since 1971), and the American Oriental Society (since 1973). Professor Nguyen was a member of the University Senate at the University of Saigon (1958-1970), Executive Committee member and staff member of the Committee for the Vietnamese Encyclopedia (1968-1970), and a member of the Societe des Etudes Indochinoises (1961-1970). In recognition of his achievements, Professor Nguyen was awarded the Culture and Education Medal in 1968. The author of four volumes of poetry (pen name Tran Hong Chau), many articles in cultural journals, and of books entitled Le Roman Vietnamien aux 18e et 19e Siecles (1955), Le Japon et le Traite de Paix (1952), and Education and Cultures in Vietnam (1970). Professor Nguyen is featured in several biographical references, including Who's Who in the World, Men of Achievement, and International Who's Who in Asian Studies. Professor Nguyen now resides in the U.S.A. (Anaheim, California).</P>
