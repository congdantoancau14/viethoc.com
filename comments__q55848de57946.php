<br />越南話的原始基語真的是漢藏語族的台語群,跟泰語、寮語算是近親,最先混合了原始的孟高棉語的成份,最後才混合了漢語,所以為何長期語言學家,會錯誤的將越南話給列入南亞語族孟高棉語群。其實越南話算是屬於漢藏語族的,因為它的聲調和音節跟台語群幾乎完全相同! 
