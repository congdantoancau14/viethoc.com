<h3>Ngữ Pháp Việt Ngữ (Grammar of the Vietnamese Language)</h3>



<b>Dưới cái nhìn của ngữ-lí-học hiện đại<br />
Giảng viên: TRẦN NGỌC NINH</B><br />
<i><br />
“…Trong khoảng nửa thế kỉ tới nay, ngữ lí học phát triển như vũ bão, đến nỗi rằng ở Âu và Mĩ châu, người ta đã không ngần ngại gọi là một cuộc cách mệnh trong trí thức, và khoa học ngôn ngữ đã lên hàng đầu của các khoa học nhân văn với những khám phá mới và những lí thuyết tân kì lan rộng sang cả triết học, tâm lí học, dân tộc học, điện cơ toán học và sự phê bình văn chương.<br />
<br />
<br />
…Nay có cả một khối sinh viên Việt nam trẻ ở Mĩ, ở Anh, ở Pháp, ở Nhật, ở Úc, ở khắp năm châu, vẫn còn chung một sinh ngữ là tiếng mẹ đẻ. Trong số sinh viên ấy, có một số học ngữ lí và một khoa học nhân văn ở trình độ đại học và đã được dẫn dắt vào những thuyết tân tiến nhất về ngôn ngữ hay về trí tuệ nhân tạo. Tôi nghĩ rằng cuốn sách này đáp ứng được một phần nào những nhu cầu mới ấy. Ngữ lí học quốc tế cũng không thể bỏ qua được một sinh ngữ có gần một trăm triệu người nói với một nền văn chương lâu dài đã gần sáu thế kỷ…”<br />
</i><br />
<br />
(Gs Trần Ngọc Ninh)<br />




<h3>Lớp Giới thiệu Chữ Nôm Cấp I, II</h3>



<b>Giảng viên: LÊ VĂN ĐẶNG<br />
</b><br />
<br />
Dành cho học viên mới bắt đầu học chữ Nôm. Học viên sẽ được học một số chữ Nôm căn bản và một số bài thơ Nôm như <i>Tự Trào</i> của Nguyễn Khuyến, <i>Tùng Thi</i> của Nguyễn Trãi, <i>Lưu Bình Diễn Ca</i>, <i>Lục Vân Tiên</i>, v.v. qua đó được học âm, nghĩa, và cách cấu tạo chữ Nôm. Khóa học gồm 10 bài thi trắc nghiệm, và một bài thi cuối khóa.<br />
<br />
