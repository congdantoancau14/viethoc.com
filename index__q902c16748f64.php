<h3>Tổng quát</h3>



<li><b>Mỗi lớp học kéo dài bao lâu?</b> - Từ 3 đến 6 tháng, tuỳ theo số lượng bài vở của từng lớp.</li>  
<li><b>Học phí? Trả bằng cách nào?</b> - Từ &#x0024;50-&#x0024;100/lớp. Trả bằng credit card (online), check, hoặc money order.</li>  
<li><b>Cách thức học?</b> - Mọi việc giảng dạy và học hành đều được thực hiện qua website này. Khi đã có account, học viên có thể download bài giảng/bài học và bài tập về máy để đọc. Nếu có thắc mắc, thảo luận, dùng <a href="./index.php?module=phpwsbb&#x0026;PHPWSBB_MAN_OP=list">Diễn đàn</a> riêng của lớp đó. Học viên làm bài thi ngay trên website này. Nếu là bài thi trắc nghiệm, thì điểm sẽ được tính và thông báo một cách tự động. Nếu là bài thi viết, giảng viên sẽ chấm bài và BDH sẽ thông báo điểm đến từng học viên. Cuối khóa học, học viên nào đủ điểm trung bình sẽ được cấp chứng chỉ.<br />
<li><b>Hạn chót ghi danh?</b> - Thường là ngày khai giảng. Chi tiết có thể tuỳ từng lớp, và sẽ được thông báo rõ ràng.</li>
<li><b>Ngày khai giảng?</b> - Khi có lớp nào đã sẵn sàng thì sẽ BDH sẽ thông báo trước 30 ngày để học viên ghi danh. Sau khi khóa học kết thúc, lớp sẽ được mở lại, sau một thời gian nghỉ ngắn hạn. Thời hạn tuỳ theo giảng viên.</li>
