<h3>Chữ Hán và Tiếng Hán Việt I, II</h3>



<b>Giảng viên: PHẠM VĂN HẢI<br />
</b><br />
<br />
Giới thiệu tổng quát về chữ Hán và tiếng Hán Việt. Tài liệu giáo khoa dựa trên quyển <i>Chữ Hán và Tiếng Hán Việt</i> (Phạm Văn Hải, Quỳnh Anh, Falls Church, Virginia, 2005, hơn 1000 trang).<br />
<br />
Cấp I: <br />
1. Tiếng Hán Việt là gì?<br />
2. Tại sao có tiếng Hán Việt trong tiếng Việt?<br />
3. Cách nhận mặt tiếng Hán Việt.<br />
4. Chữ Hán<br />
Cấp II:<br />
5. Chữ Hán – Tìm chữ<br />
<br />




<h3>Hội Luận về Nguồn Gốc Tiếng Việt</h3>



<b>Điều hợp viên: NGUYỄN HY VỌNG<br />
</b><br />
<br />
Thảo luận về nguồn gốc của tiếng Việt và mọi vấn đề liên hệ đến Việt ngữ. Bác sĩ Nguyễn Hy Vọng sẽ tặng các bạn tham dự một CD với 1500 trang / 125 ngàn tài liệu đồng nguyên của khắp 58 ngôn ngữ ĐNÁ. <br />
<br />
Học viên góp tối thiểu một tài liệu về tiếng Việt (do người khác viết, hay chính công trình của mình, bằng tiếng Việt, Anh, hoặc Pháp). Mỗi người có bổn phận trả lời cho mọi thắc mắc về tài liệu của mình. Điều hợp viên (Nguyễn Hy Vọng) sẽ trình bày và trả lời về những thắc mắc về các tài liệu nêu trên; đồng thời  kết hợp và đúc kết phần đóng góp tài liệu của mọi hội thảo viên thành một tổng luận. <br />




