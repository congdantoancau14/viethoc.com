<h3>Văn Chương Yêu Nước Miền Nam 1945-1954</h3>



<b>Giảng viên: NGUYỄN VĂN SÂM</b><br />
<br />
Khảo sát một giai đoạn văn chương đặc biệt, từ trước đến nay ít được sách vở nhắc đến: Văn chương yêu nước miền Nam 1945-1954.<br />
<br />
Các đề tài chính:<br />
<ul>
<li>Khái niệm về danh từ Nam Bộ?<br />
<li>Tại sao lại những năm 1945-1950?<br />
<li>Kháng Pháp là gì? Ai lãnh đạo?<br />
<li>Lãnh đạo hay tự phát?<br />
<li>Có sự lãnh đạo trong thời khoản nầy về mặt văn chương hay không?<br />
<li>Giai đoạn 1945-1950, văn chương Miền Nam có đáng cho chúng ta khảo sát hay không?<br />
