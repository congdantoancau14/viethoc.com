Chúng tôi thực hiện bộ "Hán Việt tự điển" Thiều Chửu dưới dạng "điện tử" với mục tiêu cống hiến cho các học sinh, những nhà nghiên cứu, … 
một phương tiện thích hợp với kỹ thuật ngày nay để học hỏi, tìm hiểu chữ Hán Việt.
<p>Chọn "Hán Việt tự điển" của Thiều Chửu, vì bộ sách này được coi là tiêu chuẩn về Hán Việt cho nhiều thế hệ người Việt Nam từ hơn 60 năm qua.  
<p>Hai ưu điểm chính của tự điển điện tử so với dạng sách in là:
<ul>
<li>Nét chữ rõ ràng
<li>Tra tìm nhanh chóng.
</ul>
<p>Khi chuyển bộ sách của Thiều Chửu sang dạng điện tử, chúng tôi hết sức tôn trọng nguyên tác.  
<p>Tuy nhiên, chúng tôi đã mạo muội thay đổi chút ít, như sau:
<ol>
<li>Thay đổi cách trình bày để thích ứng với dạng điện tử,
<li>Sửa chữa một số sai sót tìm ra dựa theo các tài liệu tham khảo có giá trị hoặc ý kiến của bậc thức giả có uy tín, trên nguyên tắc sau : 
nếu chắc chắn có sai sót thì mới sửa, nếu không cứ giữ nguyên để tồn nghi,
<li>Thiều Chửu dùng nhiều chữ cổ hơi khó hiểu cho độc giả ngày nay, chúng tôi giữ nguyên, nhưng đôi khi thêm vào định nghĩa vài chữ với 
mục tiêu duy nhất là giúp người dùng dễ dàng lãnh hội ý nghĩa của mỗi hán tự,
<li>Đánh số các định nghĩa một cách chính xác hơn,
<li>Trong nhiều trường hợp, nếu không bắt buộc phải biến đổi câu văn quá nhiều, cố gắng phân biệt chữ Việt dịch từ chữ Hán với phần giải thích 
chi tiết, điều này giúp cho các định nghĩa khỏi quá nặng nề,
<li>Thêm những thí dụ hoặc bổ túc những thí dụ có sẵn, ghi thêm xuất xứ, tên tác giả nếu tìm được, để làm sáng tỏ các định nghĩa,
<li>Nỗ lực chua thêm chữ Hán cho một số từ quan trọng trong các định nghĩa.
</ol>
<p>Vì sự hiểu biết non nớt hoặc vì thì giờ eo hẹp, nhiều sai sót không thể nào tránh khỏi, kính xin những bậc trưởng thượng vui lòng chỉ dẫn, để sửa chữa cho hoàn hảo hơn trong những phiên bản tới.
<p>Paris, 10-jan-2003
