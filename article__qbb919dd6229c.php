	<span class="type4bigger">Hát Nói: A Vietnamese musical tradition</span><br />
	Contributed by Phuong-Lan on: Tuesday 15 May @ 21:17:37
	</td>
</tr>
<tr>
		<td class="type5" background="" valign="top">
	<a href="search.php?query=&amp;topic=3&amp;author="><img src="./images/topics/vcvn_WEB.jpg" border="0" alt="Văn-chương Việt-Nam" align="right" hspace="4" /></a>Hát nói là một trong nhiều loại hát ả-đào gọi chung là ca-trù. Lối này chỉ để người nữ (ả-đào) hát với tiếng đàn đệm của một người nam (kép) cho quan-khách nghe trong đó có một người cầm chầu... <br /><hr />
<br /><h4>HÁT NÓI</h4>
<br /><p>Hát nói là một trong nhiều loại hát ả-đào gọi chung là ca-trù. Lối này chỉ để người nữ (ả-đào) hát với tiếng đàn đệm của một người nam (kép) cho quan-khách nghe trong đó có một người cầm chầu.</p>
<br /><p>Đây là một thể văn-chương xuất-hiện rất muộn trong văn-học nước nhà, muộn hơn cả thể phú. Hậu bán thế-kỷ XVIII không còn để lại một bài hát nói nào cả. Phải đợi sang tiền-bán thế-kỷ XIX mới thấy những bài hát nói của Nguyễn Công-Trứ và Cao Bá-Quát ra đời. Hát nói cũng không có một gốc-gác nào trong văn-học Trung-quốc. Vì thế, người ta vẫn công nhận hát nó là một thể-tài thuần-tuý Việt-nam và đặc-thù của thế-kỷ XIX.</br>
<br />Luật-tắc của hát nói khá phức-tạp:</p>
<br /><ol>
<br /><li>Số câu và số khổ: </li>
<br /><p>Mỗi bài hát nói đều chia ra làm từng khổ 4 câu. Nếu chỉ có hai khổ thì gọi là hát nói thiếu khổ, với ba khổ gọi là đủ khổ, và có hơn ba khổ gọi là dôi (dư) khổ.</p>
<br /><p>Đặc-biệt, khổ cuối chỉ có 3 câu thôi. Như vậy bài thiếu khổ chỉ có 7 câu (không kể mưỡu), bài đủ khổ có 11 câu...</p>
<br /><p>Căn-cứ vào kỹ-thuật xướng ca của nhà nghề, các câu trong bài đủ khổ có tên gọi chuyên-môn là:<br>
<br />* Khổ đầu: câu 1-2 gọi là lá đầu; câu 3-4 là xuyên thưa<br>
<br />* Khổ giữa: câu 5-6 gọi là thơ; câu 7-8 là xuyên mau <br>
<br />* Khổ xếp (cuối): câu 9 là dồn; câu 10 là xếp; câu 11 là keo.<br>
<br />Thí-dụ về một bài thiếu khổ: Giã-Biệt của Cung Thúc Thiềm<br>
<br /><center><i>Ngán cho nỗi xoay vần thế cục,<br>
<br />Sum-họp này chẳng bõ lúc phân-ly<br>
<br />Hỡi ông Tơ độc địa làm chi,<br>
<br />Bắt kẻ ở người đi mà nỡ được?<br>
<br />.......<br>
<br />Thôi đã trót cùng nhau nguyện-ước,<br>
<br />Duyên đôi ta chẳng trước thì sau.<br>
<br />Yêu nhau xin nhớ lời nhau!</i></center></p>
<br /><li>Số chữ trong câu: </li>
<br /><p>Số chữ trong mỗi câu không nhất-định (tự-do); thường thường, người ta làm những câu 7, 8, 9 chữ hay hơn nữa. Tuy-nhiên, biệt-cách là câu cuối chỉ có 6 chữ thôi (câu keo). Một biệt-lệ khác là hai câu 5-6 (thơ): nếu có thơ thì phải theo luật-tắc của thơ 5 chữ hoặc 7 chữ, thường là chữ Hán. Bài không có "thơ" cũng được.
<br />Thí-dụ về bài đủ khổ, Uống Rượu Tiêu Sầu của Cao Bá-Quát:<br>
<br />(khổ đầu) <center><i>Ba vạn sáu ngàn ngày là mấy,<br>
<br />Cảnh phù-du trông thấy cũng nực cười.<br>
<br />Thôi công đâu chuốc lấy sự đời,<br>
<br />Tiêu-khiển một vài chung lếu-láo!</i></center><br>
<br />(khổ giữa)	<center><i>Đoạn tống nhất sinh duy hữu tửu,<br>
<br />Trầm-tư bách-kế bất như nhàn!<br>
<br />Dưới thiều-quang, thấp-thoáng bóng Nam-san,<br>
<br />Ngoảnh mặt lại cửu-hoàn coi cũng nhỏ.</i></center><br>
<br />(khổ xếp)<center><i>Khoảng trời đất cổ kim, kim cổ,<br>
<br />Mảnh hình-hài không có, có không.<br>
<br />Lọ là thiên-tứ vạn chung!</i></center></p>
<br /><li>Cách gieo vần: </li>
<br /><p>Hát nói sử-dụng luôn một lúc cả vần bằng lẫn vần trắc ở cuối câu và yêu vận trong một số câu. Câu đầu tận cùng bằng một âm trắc không tính cước-vận (xem thí-dụ trên kia: mấy). Từ đó, cho đến hết bài cứ đôi vần bằng (cười, đời) lại đến đôi vần trắc (láo, tửu) để kết-thúc bằng đôi vần bằng (không, chung). Yêu-vận chịu ảnh-hưởng của song-thất lục- bát vừa có trắc lại vừa có bằng vận-chuyển như sau: câu đầu chuyển xướng yêu-vận trắc ở câu thứ hai (mấy và thấy); từ đó, cứ hết đôi cước-vận bằng hoặc trắc lại được tiếp-nối ở câu sau bằng một yêu-vận bằng hay trắc (từ câu 3 sang câu 4: đời và vài; từ câu 7 qua câu 8: san và hoàn; từ 9 qua 10: cổ và có) ngoại trừ hai câu thơ (5 và 6) có luật riêng của thơ không sử-dụng yêu-vận.</p>
<br /><li>Bộ-phận đặc-biệt - mưỡu:</li>
<br /><p> Một lệ tắc không bó buộc là: người làm hát nói có thể khoác thêm cho bài nào đó một bộ-phận đặc-biệt có tên là "mưỡu" viết theo thể lục-bát. Nếu thêm ở trên bài thì gọi là "mưỡu đầu"; nếu mưỡu chỉ có hai câu lục-bát thì gọi là "mưỡu đơn", có bốn hoặc sáu câu lục-bát thì gọi là "mưỡu kép" ở cuối bài nhưng trước câu keo thì gọi là "mưỡu hậu", mưỡu hậu bao giờ cũng là mưỡu đơn (hai câu lục-bát). Thí-dụ, bài "Cầm Kỳ Thi Tửu" của Nguyễn Công-Trứ :<br>
<br />(khổ đầu)<center><i>Cầm kỳ thi tửu,<br>
<br />Đường ăn chơi mỗi vẻ một hay:<br>
<br />Đàn năm cung réo-rắt tính tình đây,<br>
<br />Cờ đôi nước rập-rình xe ngựa đó.</i></center><br>
<br />(khổ giữa1)<center><i>Thơ một túi phẩm-đề câu nguyệt-lộ,<br>
<br />Rượu ba chung tiêu sái cuộc yên-hà.<br>
<br />Thú xuất trần tiên vẫn là ta, <br>
<br />Sánh Hoàng-Thạch Xích-Tùng, ờ cũng đáng! </i></center><br>
<br />(khổ giữa 2)<center><i>Cầm tứ tiêu nhiên kỳ tứ sảng,</i></center><br>
<br /> thơ<center><i>Thi hoài lạc hỷ, tửu hoài nồng.<br>
<br />Một chữ nhàn giá lại đáng thiên chung, <br>
<br />Người ở thế dẫu trăm năm là mấy.</i></center><br>
<br />(khổ xếp)  (câu dồn)<center><i>Sách có chữ "nhân-sinh thích-chí"</i></center><br>
<br />(câu xếp)<center><i>Đem ngàn vàng chác lấy chuyện cười<br>
<br />Chơi cho lịch mới là chơi,</i></center><br>
<br />(mưỡu)<center><i>Chơi cho đài-các cho đời biết tay.</i></center><br>
<br />(câu keo)<center><i>Tài-tình dễ mấy xưa nay!</i></center></p>
<br /><p>Nhận xét: Trên đây là một bài hát nói dôi khổ; có mưỡu hậu và là đơn; câu đầu không chuyển vần tửu xuống một yêu-vận trắc nào cả; có hai câu thơ thất-ngôn, chữ Hán (khổ giữa 2); câu dồn trong khổ xếp không chuyển âm-vận trắc xuống yêu-vận trắc nào cả trong câu xếp.</p>
<br /><p>Vài thí-dụ khác về mưỡu: Mưỡu đầu đơn và mưỡu hậu đơn trong bài Vịnh Tiền Xích-Bích của Nguyễn Công-Trứ; mưỡu tiền kép trong bài Hồ Hoàn Kiếm của Nguyễn Cảnh-Tuân.</p>
<br /><li>Công-dụng:</li>
<br /><p> Khởi đầu, hát nói mới có công-dụng tả cảnh, vịnh tình. Nhưng ngay sau đó, hát nói mở qua công-dụng trình-bày chí-khí hay triết-lý. Sau này, hát nói còn mở rộng hơn nữa để hô-hào tư-duy chính-trị, điển-hình baụi Nhất Sự Bất Tri của Phan Bội-Châu. Cuối cùng xuất-phát từ chốn ca-lâu, tửu-quán, hát nói dùng làm đủ mọi công việc trữ-tình nói chung và trào-phúng nói riêng . Qua thế-kỷ hiện-đại (thế-kỷ XX), chỉ còn lác-đác một số tác-giả sử-dụng và ngày nay lại càng trở nên biệt-lệ hơn nữa.</p>
<br /></ol>
<br /><i>(trích trong Văn-chương Chữ Nôm trong thế-kỷ XIX, lớp Ðại-cương Văn-học Việt-nam)</i>
