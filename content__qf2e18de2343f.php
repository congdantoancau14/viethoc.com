<p>Our correspondence programs connect you to your faculty, coursemates, and advisors through today's communication technology. Because courses at a distance do not require classroom attendance, you have the convenience and flexibility you need to balance your studies with work, family, and other important commitments. </P>
<p>Currently, we offer courses in 5 areas: Linguistics, History, Literature, Civilization, and Geography. </p>
</p>Courses are given at all levels, from beginning to advanced, by our highly qualified and experienced professors. Course books and materials, as well as access to our Research Library, are covered by the course fee. </P>
<P>A certificate is issued upon the successful completion of all lessons,  exams, and with a passing grade.</P>
<P>Our courses are designed to give those interested in the study of Vietnam a more profound understanding of the country and its culture.</P>
<P>For those seeking a more in-depth classroom-based faculty-led education instead of a correspondence course, consider our in-person (<a href="#traditional">Traditional Self-Contained</a>) classroom program.</P>
