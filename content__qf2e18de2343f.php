<P>Individual responsibility is one of the key aspects of the independent-study-by-correspondence program. It is important that you, as the student, adhere to a personal code of ethics in the completion of the course lessons and exams. Discussion of the lesson materials with other students is encouraged, but the lesson and test submissions must be your own. </P>

