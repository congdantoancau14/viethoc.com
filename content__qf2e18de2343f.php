<P>Correspondence Courses come in 9-11 lessons and at least two exams. You have two choices in the way you wish to receive lesson materials: by conventional MAIL or via Internet (WEBCLASS). Our correspondence courses are available throughout the year including the summer months. The tuition for each class is $100 which includes all class materials. The tuition must be paid in full before the class materials are sent. </P>
