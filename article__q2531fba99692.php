	<a href="search.php?query=&amp;topic=6&amp;author="><img src="./images/topics/documentacion.gif" border="0" alt="Quốc-Ngữ" align="right" hspace="4" /></a>Trích Đặc San Đền Hùng - Xuân Kỷ Tỵ 1989 - San Jose) - Lê Bắc posted in Forum-VN History (6/27/2001) <br /><h3>Ý Nghĩa Quốc Hiệu Lạc Việt </h3>https:https:https:https:https:
<br /><i>GS Vũ Thế Ngọc </i>
<br /><p>Với các tài liệu Cổ Nhân học, Nhân Chủng học và Khảo Cổ học được phát hiện trong hai thập niên qua, thêm vào những nghiên cứu của các ngành khoa học khác từ Dân Tộc học, Ngôn Ngữ học cho đến các ngành Kim Loại học, Địa Chất học ... ngày nay người ta đã có thể mang thời đại Hùng Vương vào chính sử. Thành ra phạm vi của bài viết này chỉ hết sức khiêm nhượng như là một chú thích nhỏ của một luận văn lịch sử về thời dựng nước đầu tiên của Việt tộc.</p>
<br /><p>Bài viết cũng không có những phát kiến nào mới lạ hơn là bổ xung và tổng kết những đề nghị, luận cứ của các học giả đi trước. Tuy nhiên nó cũng có một hy vọng là để chấm dứt những bài "sưu khảo" chỉ lập lại những ý kiến của Maspero, Lê Dư, Lê Chí Thiệp ... cách đây hơn nửa thế kỷ, hoặc tệ hơn nữa là các bài viết ca tụng mơ hồ cái gọi là "chim lạc".</p>
<br /><h5>Từ Ngữ Hán Việt: Hầm Bẫy Các Học Giả </h5>
<br /><p>Một thời báo chí Sài Gòn đã chế diễu một ngài tổng bộ trưởng của Việt Nam Cộng Hòa khi ông ta nhầm Nhật Nhĩ Man (chữ Hán cũ phiên âm để chỉ nước Đức: Germany, German) là nước Nhật (Japan). Nhưng nhiều người không biết là chính "trò chơi" tương tự đã là hầm bẫy biết bao học giả Việt Nam và ngoại quốc trong vấn đề nghiên cứu lịch sử, văn hóa Việt Nam. Bởi vì lý do duy nhất là tất cả tài liệu lịch sử của chúng ta đều viết bằng Hán văn, và một số không nhỏ các danh từ về nhân, vật, địa danh, danh xưng ... chỉ là chữ "ký âm" mà các vị không biết, chỉ chạy theo nghĩa tự Hán Việt.</p>
<br /><u>"Lạc" Theo Nghĩa Tự Hán Việt </u>
<br /><p>Trở lại với các tài liệu viết về cổ sử Việt Nam, ta thử tìm hiểu khi viết về Lạc Việt, lạc điền, lạc hầu, lạc tướng ... người ta viết chữ "Lạc" như thế nào và với ý nghĩa gì.</p>
<br /><p>Đầu tiên, Hán Thư (khoảng thế kỷ thứ nhất) dùng chữ <img src="http://www.chinalanguage.com/cgi-bin/char.cgi?99F1" border=0>: Lạc (mã + các), sẽ gọi là "Lạc bộ Mã", để viết chữ Lạc Việt. Thủy Kinh Chú của Lịch Đại Nguyên (đầu thế kỷ 6) là tài liệu cổ nhất có viết nhiều về sử Việt, có dẫn sách Giao Châu Ngoại Vực Ký (sách viết vào thế kỷ thứ tư, đã mất), thì viết là <img src="http://www.chinalanguage.com/cgi-bin/char.cgi?96D2" border=0>: Lạc (các + chuy), sẽ gọi là "Lạc bộ Chuy".</p>
<br /><p>Đặc biệt chỉ riêng có các sử gia Việt Nam là viết chữ <img src="http://www.chinalanguage.com/cgi-bin/char.cgi?8C89" border=0>: Lạc (trãi + các), sẽ gọi là "Lạc bộ Trãi", như trong Đại Việt Sử Ký Toàn Thư của Ngô Sĩ Liên đời nhà Lê (thế kỷ 15) (1)</p>
<br /><p>"Lạc bộ Mã", sách Tống Bản Quảng Vận đời nhà Tống cho nghĩa là "Ngựa trắng, bờm đen" (2), sách nghiên cứu về Ngữ Nguyên học của Bernhard Karlgren cũng cho nghĩa "Ngựa trắng, bờm đen" (3), Karlgren với L. Wieger còn cho một nghĩa khác là con lạc đà (4).</p>
<br /><p>"Lạc bộ Chuy", sách Quảng Vận chú nghĩa là chim Kỵ Kỳ. Chim Kỵ Kỳ (5) thì theo tự điển Từ Hải chính là chim cú mèo (otus sunia japonicus) (6), sách của Karlgren cũng chú nghĩa là một loại chim (7) cũng như sách của Wieger (8).</p>
<br /><p>Riêng về chữ "Lạc bộ Trãi", chỉ riêng có sử gia Việt là dùng. Chữ này phải đọc là Mạch (âm Quan Thoại là Mỏ) chỉ một dân tộc (rợ) phương Bắc Trung Quốc, hoặc là Hạc (âm Quan Thoại là Hao) nghĩa là một loài chồn, badger, da dùng làm áo. Chúng ta sẽ hiểu tại sao chỉ có sử gia Việt dùng chữ này ở đoạn sau.</p>
<br /><p>Với tất cả những nghĩa đó, ta thấy ngay không có nghĩa nào để chỉ dân tộc Lạc Việt, Lạc điền, Lạc tướng cho xuôi. Vì không thể nào người ta lấy tên chim cú mèo, vốn được coi như loài chim quái gở, (vì thế sau này người ta còn thay chữ "Lạc bộ Chuy" là cú mèo, thành "Lạc bộ Mã" trong các nhân danh, địa danh Trung Quốc). Trong tiếng việt còn có các thành ngữ xấu như: Mắt cú vọ, cú dòm nhà bệnh, cú kêu ra ma, cú đói ăn con v.v.... Nếu nói là vật tổ, thì từ trống đồng đến thần thoại chẳng thấy có nhắc gì đến cú mèo cả.</p>
<br /><p>Về nghĩa "Ngựa trắng bờm đen" thì cũng tương tự, hơn thế nữa, bọn trí thức phong kiến Trung Quốc, với đầu óc hẹp hòi, tự tôn và thực dân đã luôn luôn dùng những chữ bộ khuyển (chó) để chỉ những dân tộc láng giềng (Duẫn, Qua, Dao, Lào, Đồng). Chính vì không thích chữ "chó ngựa" như vậy, các sử gia Việt mới dùng chữ "Lạc bộ Trãi" để thay thế (9). Vì vậy tại sao ta thấy chỉ có sử gia Việt Nam mới dùng chữ "Lạc bộ Trãi", và cố tình "phiên thiết" sai như vậy, để chỉ rõ đây chỉ là chữ ký âm.</p>
<br /><u>"Lạc" Là Từ Tố Tiếng Việt </u>
<br /><p>Một hai học giả đã thấy được sự bất ổn khi truy nghĩa tự Lạc theo Hán văn. Người đi xa nhất là Nguyễn Kim Thản và Vương Lộc trong bài "Thử Tìm Nguồn Gốc Ngữ Nghĩa của Từ Tố "Lạc" (10).</p>
<br /><p>Như đã dẫn, sách Thủy Kinh Chú dẫn lại sách Giao Châu Ngoại Vực Ký là sách cổ nhất viết về sử nước ta viết như sau:</p>
<br /><p>"Thời xưa khi Giao Chỉ chưa có quận huyện, thì đất đai có Lạc Điền, ruộng ấy là ruộng (cầy cấy) theo con nước thủy triều. Dân khai khẩn ruộng ấy mà ăn nên gọi là Lạc Dân. Có Lạc Vương, Lạc Hầu làm chủ các quận huyện. Ở huyện phần đông có Lạc Tướng. Lạc Tướng có ấn bằng đồng, (đeo) giải (vải mầu) xanh. Về sau con vua Thục đem ba vạn lính đánh Lạc Vương Lạc Hầu, thu phục các Lạc Tướng. Con vua Thục nhân đó xưng là An Dương Vương" (11)</p>
<br /><p>Khi thấy tất cả nghĩa Hán Việt của từ Lạc đều không thỏa mãn ý của chữ Lạc trong đoạn văn trên, thì người ta đồng ý ngay là từ "Lạc" phải là từ tố tiếng Việt. Vậy tiếng cổ "Lạc" có nghĩa là gì?</p>
<br /><p>Nguyễn Kim Thản đã rất sáng mà đặt giả thuyết đó là chữ có nghĩa "nước". Tuy nhiên về chứng cớ, ông chỉ tìm được có một từ là "rạc" trong nước rạc (nước ròng), cạn rặc (cạn hết) (12). (Cũng nên biết chữ Rạc (nôm) dùng chữ Hán là "Lạc bộ Thủy" để ký âm). Thành ra phần phê bình của ông thì hợp lý, nhưng ông chưa chứng minh được giả thuyết mà ông vừa "thấy" được. Phần sau đây chúng tôi xin trình bầy để minh chứng rõ ràng "Lạc" đúng là "Nước".</p>
<br /><h5>"Lạc" là "Nước" </h5>
<br /><p>Ta hãy nhìn vào bảng tiếng chỉ "nước của các dân tộc được coi là đồng chủng (?) sau đây:</p>
<br /><p>BẢNG 1: Việt (hiện dùng): Nước - Mạ: Đa - Churu: Đạ - Koho: Đa - Nup: Đa - Muong: Đa - Bana: Đák - Sơ Đăng: Đák - Cua: Đaák - Xi Tiêng: Đaác - Mường: Rác - Việt (tiếng địa phương bắc Trung Bộ): Nác<br>
<br />(Nên nhớ vùng "tiếng địa phương bắc Trung Bộ" vẫn được các nhà ngữ học coi là nơi duy nhất còn giữ được nhiều tiếng cổ Việt)</p>
<br /><p>Như vậy ta thấy rõ rệt Nác, hay Đák chính là cổ âm của từ "Nước".</p>
<br /><p>Nay chỉ còn mấu chốt giải thích từ âm tự "Nác" biến thành "Nước". Chúng ta sẽ chứng minh có sự biến đổ từ âm "A" thành "Ươ" như Nguyễn Kim Thản đề nghị (13), ta có thể theo dõi các bảng so sánh sau đây:</p>
<br /><p>BẢNG 2: a) So sánh tiếng địa phương bắc Trung Bộ (cổ hơn) với tiếng địa phương Bắc Bộ: Nác - Nước, Náng - Nướng
<br />b) Tiếng Mường (được xem là gần với cổ Việt) so với tiếng Việt hiện đại: Rác - Nước, Lái - Lưới<br>
<br />Đặc biệt là tiếng Việt hiện nay ta còn thấy rất nhiều tiếng tương đương đang được dùng lẫn cho nhau:</p>
<br /><p>BẢNG 3: Bang / Bương (Bương ra) <br>
<br />Chàng / Chường (anh chường) <br>
<br />Đàng / Đường (đường đi) <br>
<br />Đang / Đương (đương cai) <br>
<br />Nàng / Nường (nõn nường) <br>
<br />Nhạt / Nhược (nhường nhược) <br>
<br />Nập / Nượp ( đi nượp nượp) <br>
<br />Rám / Rướm (rướm nắng) <br>
<br />Rán / Rướn (rướn cổ) <br>
<br />Tan / Tương (rách tương) <br>
<br />Đặc biệt hơn nữa là những từ Hán Việt âm "A" cũng thường được "nôm hóa" bằng "Ươ"</p>
<br /><p>BẢNG 4: Khang / Khương (an khương) <br>
<br />Lạng / Lượng (một lượng) <br>
<br />Lang / Lương (lương đống) <br>
<br />Phang / Phương (phương hướng) <br>
<br />Phan / Phướn (cây phướn) <br>
<br />Phạt / Phược (thọ phược) <br>
<br />Thang / Thương (vua Thương) <br>
<br />Không những các âm "A" biến đổi với âm "Ươ" như trên, mà phụ âm L/N/R còn cũng có thể thay đổi lẫn nhaụ Thí dụ xem bảng 5. Nên nhớ R, Đ, N, L đều là âm Răng Nướu (Dental Alveolar) chỉ khác nhau ở độ cong lưỡi.</p>
<br /><p>BẢNG 5: Nác - Lạc - Rác <br>
<br />Năm - Lăm (mười) - Rằm (mười) <br>
<br />Nơi - Lơi - Rơi <br>
<br />Nép - Lép - Rẹp <br>
<br />Nung - Lung (lay) - Rung <br>
<br />Nỉ (non) - Lí (nhí) - Rỉ (rê) <br>
<br />Nêu - Lêu (...!) - Rêu </p>
<br /><p>Ắt chúng ta còn biết một số lớn người không phát được âm L (ông Nái Nợn ...) Đặc biệt là tất cả dân Việt vùng biển Bắc Bộ đều phát âm L thành N.</p>
<br /><p>Theo luật Ngữ học thì âm nào càng dễ đọc và được đại đa số người ta phát âm được thì càng cổ hơn. (Đó cũng là trường hợp đại đa số dân Việt Bắc Bộ không phát được âm TR (vì âm đó không có trong Việt Ngữ, là sự ký âm sai của các giáo sĩ ngoại quốc). Như vậy âm "N" chắc chắng phải có trước âm L.</p>
<br /><p>Tuy nhiên cũng cần nên biết về Ngữ Âm học lịch sử từ nguyên học (Etymology) thì người ta chỉ chú trọng đến từ căn (root) còn các phụ âm đầu (prefix), phụ âm cuối (suffix) thì rất biến đổi theo thời gian và không gian. Cũng như chỉ chú ý đến Âm Tố (Phoneme) chứ không chú ý đến các ký hiệu ký âm.</p>
<br /><p>Nhưng còn chữ Lạc nếu chỉ là ký âm thì người Trung Quốc đọc như thế nào ? Điều quan trọng là phải biết họ phát âm ở thời cổ như thế nào?</p>
<br /><p>Thật may mắn, công trình nghiên cứu về cổ âm Hán đã được nhà Trung Hoa học nổi tiếng Karlgren nghiên cứu. Tra từ điển của ông ta thấy cổ âm hán đọc cả ba chữ Lạc (bộ mã, bộ chuy, bộ thủy) đều được đọc là "Lak" (14). (Ngày nay người Bắc kinh đọc là Lo). Khi nghiên cứu các bản văn Phạn ngữ ký âm bằng Hán tự, phát hiện được ở động Đôn Hoàng, chúng tôi đã kiểm chứng lại sự chính xác của Karlgren (15).</p>
<br /><p>Thành ra chữ Lạc Điền chỉ là Ruộng Nước, chữ Lạc là chữ ký âm chẳng khác nào chữ Dã Thụ là cây Dừa (Dà là chữ ký âm của Dừa), Ba La Mật Thụ là cây B'La Mít (cây mít), Phù là Bìu (trầu) v.v...</p>
<br /><p>Nhưng ruộng nước là ruộng gì? Có gì đặc biệt ở đó? Phải nên biết Hán tộc bắc phương, đất tổ là phía bắc Hoàng Hà chỉ biết trồng lúa mì (ruộng khô). Phương nam mới là nơi trưởng sinh ra phương pháp trồng lúa gạo (ruộng nước).</p>
<br /><p>Muốn trồng được lúa gạo, con người phải đạt được trình độ văn minh cao hơn hết thẩy so với các hoạt động kinh tế nông nghiệp khác, vì họ phải biết tính toán được chu kỳ thiên văn, điều thủy .... bên cạnh các kỹ thuật như làm ra được lưỡi cầy và thuần phục được trâu (15b) (là giống vật duy nhất để cấy được ruộng nước, vốn là một con thú hoang dữ tợn và to lớn) v.v....</p>
<br /><p>Vì vậy dân tộc đầu tiên làm chủ được ruộng nước, ắt phải kiêu hãnh lắm (so với tình trạng thời đó, thì còn hơn là các nước Âu châu trong thời gian "cách mạng kinh tế" của thế kỷ 19 nhiều). Thế mà dân Lạc Việt lại là dân tộc đầu tiên trên thế giới biết đến nó, cuộc khai quật của Wilheim G. Solheim, thuộc đại học Hawaii lại cho thấy sau khi thử phóng xa C-14, mẫu lúa của người Hòa Bình, cho niên đại là khoảng 3500 trước Tây Lịch, sớm hơn ở Ấn Độ và Trung Quốc khoảng 1000 năm, nơi mà người ta vẫn cho là quê hương của loại lúa trồng này (16). Solheim còn tin là nếu tiếp tục tìm kiếm người ta có thể tìm được mẫu lúa, chứng tỏ là người Lạc Việt đã biết trồng lúa hơn bốn ngàn năm trước Tây lịch (17). Cũng nên nhắc ở đây là qua các cuộc đào tìm này người ta đã minh chứng một số chứng liệu cụ thể khác như nền văn hóa Hòa Bình biết đến kim loại sớm nhất thế giới, biết làm đồ gốm sớm nhất thế giới .... (18). Nhà địa chất học Hoa Kỳ Carl Sauer từ năm 1952 cũng đã đặt giả thuyết chính người Hòa Bình biết đến nông nghiệp sớm hơn hết, giả thuyết này cho đến năm 1966 thì được các giáo sư của các đại học Otago (Tân Tây Lan), Hawaii (Hoa Kỳ) chứng minh bằng các mẫu đậu với niên đại cho bởi phóng xạ C-14 là 10 ngàn năm trước Tây lịch (19). Cuối cùng Solheim đặt giả thuyết nền văn hóa Hòa Bình, ở Bắc Việt Nam có thể đã là gốc mẹ của nền văn hóa Lưỡng Thiều Trung Quốc (nơi phát tích ra văn hóa Trung Quốc) (20).</p>
<br /><p>Trở lại với từ tố "Lạc", như vậy chúng ta đã đi qua được các chặng đường:</p>
<br /><ol>
<br /><li>Minh chứng "Lạc" là Nước, cổ âm của tiếng Việt và cổ Hán cũng trùng hợp như vậy (21).</li>
<br /><li>Dân Lạc Việt bản địa là chủ nhân https:iên trên thế giới biết về nghề làm "ruộng nước" (lúa gạo) và rất hãnh diện khi nhận mình là "Lạc dân" (không thể hiểu là "người nước" (22) như Nguyễn Kim Thản viết, mà nên hiểu là "người có ruộng nước", "người làm chủ ruộng lúa", "người biết làm nghề nông", giống như là "Engineer, Actor, Artist, Administrator ... Mặc dù không ai phủ nhận là nền văn hóa của chúng ta cho đến hiện nay vẫn đặt cơ sở trên nền kinh tế thuộc về "nước" (nói theo kiểu Hydraulic Society), yếu tố "sông nước" không thể tách rời khỏi văn hóa Việt: Long Quân ... theo cha xuống biển ... người trong một nước .... như tác giả đã viết). Vậy thì để trả lời câu hỏi là Hùng Vương hay Lạc Vương của các cụ đặt ra từ trước 1945, ta trả lời thế nào?
<br /></li>
<br /></ol></p>
<br /><p>KẾT LUẬN: Lạc Vương là Hùng Vương.<br>
<br />Không có vấn đề viết nhầm.<br>
<br />Kết luận ta có thể thoải mái mà hiểu rằng từ Lạc trong Lạc Việt, Lạc Điền, Lạc Tướng ... dù viết theo "Lạc bộ Chuy", "Lạc bộ Mã" hay "Lạc bộ Trãi", đều chỉ là chữ ký âm, và ngày nay với chữ quốc ngữ, vô tình vấn đề đã được giải quyết: chúng ta chỉ còn một chữ Lạc.</p>
<br /><p>Để tìm hiểu Lạc có nghĩa là gì hy vọng bài này đã giải quyết được câu hỏi đó. Nhưng trở lại câu hỏi, vậy thì là Hùng Vương hay Lạc Vương? Chúng tôi đề nghị lời giải đáp như sau:</p>
<br /><p>Trước hết về thư tịch, sách cổ hơn hết là Giao Châu Ngoại Vực Ký (thế kỷ thứ 4) do sách Thủy Kinh Chú (thế kỷ thứ 6) dẫn lại (xem phần trên) thì đều viết là Lạc (Lạc Vương, Lạc Điền, Lạc Tướng ... ) Trái lại sách Nam Việt Chí (thế kỷ thứ 5) do sách Sơ Học Ký (thế kỷ thứ 7) dẫn lại thì đều viết là Hùng (Hùng Vương, Hùng Điền ....)</p>
<br /><p>Riêng sách sử chúng ta viết về sau, nhưng đặc biệt là tất cả đều viết là Lạc (xem phần trên), trừ danh từ duy nhất là Hùng Vương, thì viết chữ <img src="http://www.chinalanguage.com/cgi-bin/char.cgi?96C4" border=0>:  Hùng (xem các sách Lĩnh Nam Chích Quái, Việt Điện U Linh, Việt Sử Lược, Đại Việt Sử Ký Toàn Thư, v.v....)</p>
<br /><p>Sử gia Ngô Sĩ Liên còn cho biết: (trước là) Lạc Tướng sau lầm ra Hùng Tướng (Lạc Tướng hậu ngọa vi Hùng Tướng) (23)</p>
<br /><p>Trước đệ nhị thế chiến H. Maspero đọc Hán Thư cho thấy trước thế kỷ thứ 5 sách Trung Quốc chỉ dùng từ ngữ Lạc Vương và từ ngữ Hùng Vương chỉ thấy xuất hiện từ sau Nam Việt Chí (thế kỷ thứ 5) nên chủ trương chỉ có Lạc Vương, sở dĩ có từ Hùng Vương vì viết nhầm chữ Lạc (các + chuy) thành chữ Hùng (quang + chuy). Đó có lẽ cũng là lý của Ngô Sĩ Liên (24).</p>
<br /><p>Lê Dư và hầu hết các học giả Việt Nam sau này, đều chủ trương Hùng Vương bởi các lẽ:</p>
<br /><ol>
<br /><li>Lạc Vương là chữ do người Trung Quốc dùng để ghi tên Vua nước Lạc, chữ Hùng Vương mới là tên hiệu của tổ nước Việt.</li>
<br /><li>Chữ Lạc trong từ Lạc Việt viết với bộ trãi, và bộ mã thì không thể lầm với chữ Hùng được.</li>
<br /><li>Tất cả trong dã sử, truyền thuyết Việt ... qua đến các di tích lịch sử đều viết hoặc mang danh hiệu Hùng Vương (xem các truyện Nhất Dạ Trạch, Đổng Thiên Vương, Lý Ông Trọng ... các địa danh Đền Hùng, Núi Hùng ....)</li></ol></p>
<br /><p>Cuộc tranh luận cho đến nay chưa xong ... cho đến hôm nay.</p>
<br /><p>Chúng tôi mới được một giáo sư đồng nghiệp giới thiệu cho biết cuốn sách mang tên là Thuyết Văn Thông Huấn Định Thanh của Chu Tuấn Thanh thì cho thấy chữ Lạc bộ Chuy có thể được thay thế bằng chữ <img src="http://www.chinalanguage.com/cgi-bin/char.cgi?96C4" border=0>: Hùng (quang + chuy): chứng cớ tên Lạc Đào nhân vật trong sách Hán Thư, phần cổ kim nhân biểu (Lạc Đào là bạn vua Thuấn) đã được Thi Hiệu (mưu sĩ của tể tướng đời Tần là Thương Ưởng), tác giả Thi Tử Thập Nhị Thiên đổi tên là Hùng Đào.</p>
<br /><p>Tóm lại, chúng tôi đã trình bày ý nghĩa của từ Lạc chỉ có nghĩa là Nước. Vì nhu cầu ghi chú, sử sách cả ta lẫn Trung Quốc bắt buộc phải dùng Hán tự để ghi chép. Riêng người Việt chúng ta thích dùng chữ Lạc bộ Trãi vì ghét nghĩa đen của hai chữ Lạc kia: (Ngựa trắng bờm đen, cú vọ). Việc này chỉ xẩy ra khi ta tiếp xúc với Hán tộc và biết dùng Hán tự.</p>
<br /><p>Tuy nhiên theo nghĩa đen thì cả chữ Lạc đều chẳng tốt đẹp gì. Còn chữ Hùng thì thật là tốt đẹp hơn (đực, trống, mạnh) như trong các từ anh hùng, hùng tráng, hùng hồn, hùng dũng .... Vậy thì khi biết được Hán tự, có thể chẳng cần biết đến chữ nọ thay được chữ kia, dân Lạc Việt cũng đã tự động tôn xưng vị lãnh đạo là Hùng Vương rồi. Thế mà tiền lệ Hùng Đạo đã có từ ba trăm năm trước tây lịch, thì đương nhiên dân Lạc Việt phải gọi vị quốc tổ mình là Hùng Vương thì càng đúng. Cho nên mãi đến sau này mọi truyện thần thoại hay địa danh dân đều kính trọng mà gọi là Hùng Vương, hội đền Hùng v.v.... Tóm lại, Hùng là chữ khác của chữ Lạc, là danh từ Lạc dân tôn xưng Vua của mình, không thể có chuyện viết lầm như H. Maspero hay Ngô Sĩ Liên đã viết.</p>
<br /><p>Riêng về các từ khác, Lạc điền, Lạc tướng, Lạc hầu .... thì hoặc vì tôn trọng vị lãnh tụ nên ông Lạc hầu chẳng dám nhận người ta gọi mình là Hùng hầu, hoặc vì Hùng điền thì đi quá xa nghĩa nguyên thủy là ruộng nước ... nên dân Việt vẫn tiếp tục dùng Lạc điền, Lạc hầu .... Cho nên đến tận ngày nay chúng ta vẫn chỉ dùng chữ Hùng Vương, còn tất cả đều là Lạc hết: Lạc hầu, Lạc tướng, ruộng lạc ....</p>
<br /><p>Riêng về quyển sách Nam Việt Chí của Thẩm Hoài Viễn, thì ngày nay không còn, đâu đó chỉ là những đoạn được chép lại trong Sơ Học Ký (thế kỷ thứ 7), trong Thái Bình Hoàn Vũ Ký của Nhạc Sử đời Tống (thế kỷ thứ 10) mà có lẽ đoản văn được nhiều người dẫn đi dẫn lại "Giao Chỉ có ruộng, người ta gọi ruộng ấy là Hùng Điền, dân ấy là Hùng Dân, quân trưởng là Hùng Vương, hữu ty là Hùng Hầu, đất đai chia cho các Hùng Tướng". Xem thì thật giống đoạn dẫn ở Thủy Kinh Chú (đã dẫn ở phần trên). Có điểm khác là Nam Việt Chí thì toàn dùng chữ Hùng.</p>
<br /><p>Điều này cũng dễ giải thích, hoặc là ông không còn biết từ tố "Lạc" là Nước, và theo lối thay chữ của Thi Hiệu, ông dùng Hùng thay cho chữ Lạc có nghĩa đen không tốt đẹp gì vì lý do thanh nhã, lịch sự (chắc ông phải có cảm tình gì lắm mới để tâm huyết mà viết quyển Nam Việt Chí kia). Sử cũng nói rằng ông đã từng sống ở Giao Chỉ thì ắt ông cũng biết về lý do người Lạc Việt gọi ông tổ họ là Hùng Vương. Trái lại tác giả Thủy Kinh Chú và Giao Châu Ngoại Vực Ký là quan lại của Trung Quốc, một quốc gia phong kiến đang đô hộ dân Việt, ắt họ dùng "Lạc bộ Mã" với nghĩa đen là "Ngựa trắng bờm đen" thì cũng đúng là "sách lược khai hóa man di" lắm vậy.</p>
<br /><i>Bát Bất Đường, San Jose Mùa Xuân<br>
<br />Vũ Thế Ngọc</i>
