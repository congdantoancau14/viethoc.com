               <td class="type5" width="90%" valign="top"><span class="boldtext"><center>GIÁO SƯ ĐÀM TRUNG PHÁP</center></span><br /><p><img src="images/user_pages/3sm.jpg" align="left">Sau khi đậu tú tài toàn phần ban văn chương tại  Saigon, thanh niên 18 tuổi Ðàm Trung Pháp được học bổng quốc gia du học Hoa Kỳ năm 1959. Lần lượt tốt nghiệp cử nhân văn chương Anh tại Miami University năm 1962 và cao học ngữ học năm 1964 tại Georgetown University, cũng là nơi ông đang theo học ban tiến sĩ ngữ học thì được lệnh trở về nước năm 1965. Sau đó tại quê nhà, ông hoàn tất chương trình tiến sĩ giáo dục tại Ðại Học Sư Phạm Saigon vào đầu năm 1975. Luận án của văn bằng này đã được tác giả tóm lược lại thành một chuyên khảo sư phạm mang tên "A Contrastive Approach for Teaching English as a Second Language to Vietnamese Speakers" do cơ quan nghiên cứu giáo dục song ngữ Intercultural Development Research Association (IDRA) tại San Antonio, Texas xuất bản và phổ biến đến các khu học chánh cũng như các trường đại học Hoa Kỳ  vào giữa năm 1980.</p>
<p>Giáo sư Ðàm Trung Pháp hiện là giáo sư ngôn ngữ học kiêm giám đốc các chương trình đào tạo giáo chức song ngữ (Tây ban nha và Anh ngữ) và giáo chức ESL ở bậc cử nhân và hậu cử nhân tại Texas Woman's University. Trước năm 1975, ông là giám đốc Trung Tâm Sinh Ngữ kiêm giáo sư Anh ngữ tại Ðại Học Sư Phạm thuộc Viện Ðại Học Saigon. Từ ngày qua Texas tỵ nạn, ông cũng đã từng dạy tại East Texas State University, University of Texas at Dallas, và đảm nhiệm chức vụ giám đốc ngoại ngữ cho Khu Học Chánh Dallas. Là người rất thiết tha đến sự sống còn của  tiếng Việt tại hải ngoại, ông đã thành công trong nỗ lực vận động cho ngôn ngữ và văn hóa Việt Nam được hội nhập vào học trình trung học của Khu Học Chánh Dallas từ năm 1992. </p>
<p>Giáo sư Ðàm Trung Pháp đã xuất bản các tác phẩm giáo khoa liệt kê dưới đây:</p>
<ul>
<li>Fundamentals of American English Phonology   (Faculty of Pedagogy, University of Saigon, 1972).</li>
<li>Fundamentals of American English Syntax      (Faculty of Pedagogy, University of Saigon, 1974).</li>
<li>A Contrastive Approach for Teaching ESL to Vietnamese Speakers  (Intercultural Development Research Association, San Antonio, Texas, 1980).</li>
<li>A Manual for Teachers of Indochinese Students  (Intercultural Development Research Association, San Antonio, Texas, 1981)</li>
<li>Teaching Linguistically Different Learners  (joint author) (Federation of North Texas Area Universities Press, 1991).</li>
<li>Instructional Guide for World Languages  (Dallas Independent School District, 1994).</li>
</ul>
<p>Giáo Sư Ðàm Trung Pháp là một diễn giả rất được ái mộ trong các hội nghị giáo dục ngôn ngữ từ nhiều năm nay tại Hoa Kỳ, và một số bài diễn thuyết chủ đề (keynote speeches) của ông đã được cơ quan ERIC Clearinghouse on Language and Linguistics tại Washington, DC phổ biến rộng rãi. Oâng cũng là một cố vấn chuyên môn về phương pháp giảng dạy ESL và giáo dục đa văn hóa cho hai nhà xuất bản sách giáo khoa Houghton-Mifflin và Rigby.</p>



