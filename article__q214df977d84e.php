	<a href="search.php?query=&amp;topic=3&amp;author="><img src="./images/topics/vcvn_WEB.jpg" border="0" alt="Văn-chương Việt-Nam" align="right" hspace="4" /></a>Phạm Duy có đề tên một bản nhạc “Em hiền như ma sœur” và Phạm văn Hải, khiêm tốn hơn, viết: “Em hiền như hoa cỏ” .  Tuy không là nhà thơ chuyên nghiệp, Phạm Văn Hải hằng năm vào dịp giổ người vợ xinh xinh bé nhỏ, thanh thanh, hiền như hoa cỏ, đều có làm một bài Thơ Tình. Chúng tôi có dịp đọc bài Thơ Tình Thứ Nhứt, Dung Xưa, làm 15 năm trước đây. 
<br />
<br /> <br />Lúc xa cách
<br />	...
<br />	Mỗi người một ngả,
<br />	Nàng đi xứ lạ quê người.
<br />	Tôi ở lại một mình thui-thủi.
<br />	Suốt mấy mùa đông,
<br />	Biết bao sầu-tủi.
<br />	Ngoài trời không lạnh,
<br />Trong lòng tựa giá-băng.
<br />	...
<br />	“Bốn năm lâu lắm,
<br />	Tình nào còn thắm!
<br />Anh chẳng còn nhớ tới Dung đâu!”
<br />
<br />Rồi cũng có ngày sum họp.
<br />		...
<br />	Ngày trở về,
<br />	Phố-phường hoa nở,
<br />	Tôi ngỡ là mơ.
<br />	“Thế mà em sợ
<br />	Tình mình dang-dở!”
<br />Họp rồi tan.
<br />	...
<br />	Ai ngờ loạn nổi khắp nơi.
<br />	Chồng ở phương xa,
<br />	Vợ ở nhà trông-ngóng.
<br />Tan rồi lại hợp.
<br />	Đúng ba năm,
<br />	Tôi được thả.
<br />Hai mươi sáu năm sau, người em hiền hơn hoa cỏ, người yêu bé-nhỏ xinh-xinh thỏ thẻ bên tai:
<br />	“...
<br />	Lúc gần nhau phải nghĩ đến cách-xa.”
<br />và
<br />	Một buổi sáng mờ-mờ trời chưa nắng,
<br />	Nàng ra đi không hẹn ngày về.
<br />
<br />Sau khi chuyển nhập xong phần Chữ Nôm, chúng tôi được phép tác giả cho đăng lại trên Trang Nhà Việt Học bài <a href="http://www.viethoc.org/eholdings/DungXua_Rev-2.pdf" target="new_target">Dung Xưa</a>.
<br />
<br />Kính mời quý vị vào <a href="http://www.viethoc.org/content.php?menu=24&page_id=47" target="new_target">Việt-Học Thư Quán</a> đọc một câu chuyện tình nhẹ như mây, trong như thuỷ tinh hầu cùng tác giả ôn lại một kỷ niệm xưa, nhớ người em bé nhỏ xinh xinh.
<br />
