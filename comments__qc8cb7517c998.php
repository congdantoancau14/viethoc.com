<p>The Vietnam Culture Series is an endeavor to disseminate scholarly information on the various aspects of Vietnamese culture to the reading public. Through this series, the Institute of Vietnamese Studies will publish periodic monographs focusing on such major areas as Nom literature and philosophy, Vietnamese classical and modern literatures, history, geography, and cultural anthropology.</p>
<p>For this first monograph of the Vietnam Culture Series, we have collected four papers on Nom literature, in which a linguist and lexicographer, a philologist, and a scientist share their views on the Nom characters.</p>
<p>On subsequent monographs will disseminate a number of out-of-print and hard-to-find articles by notable scholars of Vietnamese studies and, hopefully, articles by contemporary researchers.</p>
