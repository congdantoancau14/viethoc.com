<p><img src="./images/main_page/chuyenkhaosm.jpg" border="0" alt="The Institute of Vietnamese Studies" align="left" hspace="5" vspace="5" />Tập Tài Liệu về Văn Hoá Việt Nam (Vietnam Culture Series) là một cố gắng nhằm phổ biến tới học giới những kiến thức về văn hóa Việt Nam dưới nhiều khía cạnh khác nhau. Qua loạt ấn phẩm này, Viện Việt-học sẽ xuất bản những tập chuyên khảo bất định kỳ, tập trung vào những lãnh vực như chữ Nôm, cổ và kim văn, sử địa và dân tộc học...</p>
<p>Trong tập đầu tiên của loạt chuyên khảo này, chúng tôi sưu tập để giới thiệu bốn bài biên khảo về văn học chữ Nôm, trong đó một nhà ngữ học và biên soạn tự điển, một nhà ngôn ngữ học và một khoa học gia chia sẻ quan điểm của các vị về chữ Nôm.</p>
<p>Trong các tập kế tiếp, một số bài biên khảo khó kiếm hay đã tuyệt bản của các học giả có uy tín về Việt-học cùng các bài nghiên cứu, nhận định mới nếu có thể cũng sẽ được phổ biến. </p>
<p>Chúng tôi hy vọng quý vị độc giả sẽ thấy loạt ấn phẩm này có điểm hữu ích.</p>
<p>Quý vị độc giả muốn đặt mua tập Tài Liệu về Văn Hoá Việt Nam số 1 - Chuyên Khảo về Chữ Nôm (Vietnam Culture Series No. 1 - Monograph On Nôm Characters) xin liên lạc với chúng tôi qua email <a href="mailto:admin@viethoc.org">admin@viethoc.org</a> hoặc gửi bưu phiếu về địa chỉ : 15355 Brookhurst St., Suite 222, Westminster, CA 92683, USA</p><p>Giá bán: 20.00 Mỹ Kim</p>
