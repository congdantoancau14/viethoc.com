	<a href="search.php?query=&amp;topic=3&amp;author="><img src="./images/topics/vcvn_WEB.jpg" border="0" alt="Văn-chương Việt-Nam" align="right" hspace="4" /></a>Ðể tiếp tục <i>Thảo Án Chinh Phụ Ngâm</i>, <b>Viện Việt Học</b> hân hạnh giới thiệu bạn <i>Lê Sơn Thanh</i>, quản thủ thư viện <b>Trường Viễn Ðông Bác Cổ Paris (École Française d’Extrême Orient, Paris)</b>, diễn dịch và chú thích bài Nguyên tựa Chinh phụ ngâm diễn âm.<br /> <br /><br />Sau đây là đoạn đầu bài Nguyên Tựa.<br /><br /><center>征 婦 吟 演 音 新 曲 元 序</center><br />以 本 國 音 語 演 中 國 文 字 最 難, 蓋 中 國 文 字, 詩 餘 而 外 爲 歌 調 詞 格 體 製 繁 極. 其 措 意 運 語 高 下 疾 徐. 用 所 縱 聘 國 音 則 傷 於 局 逼, 施 諸 韻 律, 惟 挽 歌 與 詞 曲 二 體 句 法 無 他 也. 解 北 字 而 用 南 音, 不 失 之 鑿, 則 流 之 野. 亦 其 勢 難 矣.<br /><br /><center>Nguyên tựa Chinh phụ ngâm diễn âm tân khúc</center><br />Lấy quốc âm mà diễn văn tự Trung Quốc thì hết sức khó khăn. Vì văn tự Trung Quốc, ngoài thơ ra, còn có ca điệu và từ cách mà thể chế thì cực kỳ nhiều. Đặt ý thì vận dụng ngôn từ khi cao khi thấp, khi nhanh khi chậm. Nếu dùng cái phóng túng của mình (?) thì quốc âm sẽ chịu thiệt thòi ở sự câu thúc của bố cục. Và nếu dùng các loại vận luật thì chỉ có vãn ca và từ khúc thì không khác nhau về cú pháp. Khi giải chữ phương Bắc mà lấy tiếng Nam thì không mất ở chỗ xuyên tạc thì cũng rơi vào chỗ quê mùa. Cái thế đó cũng khó vậy thay.<br /><br />Kính mời quý thân hữu vào <a href="/content.php?menu=24&page_id=47">Việt Học Thư Quán</a> đọc trọn phần <a href="/eholdings/BaiTua_CPNK.pdf">Giới Thiệu bài Tựa</a> hiếm quý này.<br /><br /><i>Lê Văn Ðặng</i>
