	<td class="type4" width="100%">
	<span class="italic">Văn-chương truyền khẩu: Tục-ngữ - Ca-dao - Truyện cổ-tích (1)</span>&nbsp;<br /> by: Phuong-Lan on: Friday 18 May @ 17:00:36</td></tr><tr><td class="type5"><h4>Văn-chương truyền khẩu</h4>
<p>Người là sinh vật biết nhận thức, có ý nghĩ, tình cảm, và khả năng diễn đạt những ý nghĩ, tình cảm ấy. Trong lịch sử văn học của các dân tộc, trước khi tiến tới giai đoạn có chữ viết với những sáng tác được ghi chép thành văn, trong dân gian đã có:
<li>những câu nói ngắn, gọn có ý nghĩa;</li>
<li>những câu hát theo giọng điệu tự nhiên để biểu lộ, gửi gấm tình cảm;</li>
<li>những mẩu chuyện để cắt nghĩa các hiện tượng thiên nhiên hay các tập tục, tín ngưỡng.</li><p>Văn học dân gian truyền khẩu (với những tục ngữ, ca dao, truyện cổ tích... ) xuất hiện trong rất nhiều xã hội trước khi con người tìm ra chữ viết. Trong văn học sử Trung hoa, khởi đầu cho thơ ca chính là những câu hát dân gian mà về sau Khổng tử đã sưu tập lại trong Kinh Thi. Tục ngữ, ca dao và truyện cổ tích (proverbs, folk songs, folk poetry, folk tales, hay nói chung, folk literature) là tài liệu văn học quan trọng của nhiều dân tộc trên thế giôùi, không riêng gì dân tộc Việt Nam.</p>
<p>Đối với dân tộc ta, dòng văn học dân gian có một địa vị đáng kể hơn thế nữa. Suốt trên 1000 năm Bắc thuộc, văn tự chính thức được công nhận là chữ Hán, thứ chữ không diễn đạt được tiếng nói của dân Việt. Sau khi lấy lại được chủ quyền, tuy tiền nhân ta có thêm chữ nôm, nhưng chữ này khó học, khó nhớ vì lại do chữ Hán ghép thành (muốn biết chữ nôm phải thông thạo chữ Hán trước). Vì thế trong xã hội ta xưa, số người biết đọc, biết viết để có thể diễn đạt ý tưởng, tình cảm bằng chữ (bất kể chữ nôm hay chữ Hán) rất ít. Đại đa số dân chúng đã sáng tác và lưu giữ các tác phẩm dưới dạng truyền khẩu. Chính vì thế, dòng văn học dân gian truyền khẩu rất phong phú và quan trọng trong kho tàng văn học Việt Nam.</p>
<p>Văn học truyền khẩu không hoàn toàn là sáng tác của người bình dân ít học. Trước khi thành đạt, đa số nho sĩ sinh sống, học hành ở thôn quê. Nhiều ẩn sĩ, hàn nho ở với nông thôn suốt đời. Trong những dịp hội hè, trong các cuộc gặp gỡ, hát xướng, nhiều câu nói, câu hát của các vị đã được người bình dân ít học ghi nhớ rồi từ đó, gia nhập dòng văn học dân gian. Theo nhiều tài liệu, Trạng nguyên Lương Thế Vinh (ông Trạng Lường), thi hào Nguyễn Du (cậu Chiêu Bảy), nhà cách mạng Phan Bội Châu (ông Giải San), nhà thơ Nguyễn Bính... đều đã từng tham dự các sinh hoạt ca hát ở thôn quê và có tác phẩm để lại, làm giàu thêm cho kho tàng văn học dân gian. Ta có thể tin nhiều nho sĩ, trí thức khác cũng đã có những hành động tương tự.</p>
<h4>TỤC-NGỮ</h4>
<ol>
<li>Định nghĩa và biệt loại:</li>
<p>Tục ngữ (tục: thói quen có đã lâu đời; ngữ: lời nói) là những câu nói ngắn, gọn, giàu ý nghĩa, được dùng trong lời nói hàng ngày và lưu truyền từ đời nọ qua đời kia. Tục ngữ còn được gọi là ngạn ngữ (lời người xưa truyền lại).<br>
Có ý nghĩa hẹp hơn tục ngữ là:</p>
<ul>
<li>Phương ngôn: 
Những câu tục ngữ được dùng trong một vùng, một địa phương chứ không phổ biến khắp nước.</li>
<li>Cách ngôn, Châm ngôn: 
Những câu tục ngữ có ý khuyên dạy luân lý ("cách" là phương thức, "châm" là lời răn bảo).</li> 
<li>Thành ngữ:
Một loại tục ngữ đặc biệt, tự nó chưa có ý nghĩa đầy đủ. Thành ngữ chỉ là những cách nói đã định sẵn (set expressions) để mô tả sự vật chứ không biểu thị một ý phán đoán hay khuyên răn nào. Chẳng hạn:<br>
<center><i>
Đàn gảy tai trâu<br>
Đáy bể mò kim<br>
Nói hươu nói vượn<br>
Gần đất xa trời<br>
Tránh vỏ dưa gặp vỏ dừa<br>
Ngậm bồ hòn làm ngọt<br>
Cảnh trứng chọi với đá<br>
Chốn miệng hùm nọc rắn<br>
Xứ tiền rừng bạc biển...</i></center>
Trong các thành ngữ, có những câu diễn ý so sánh hai sự vật để làm nổi bật việc mô tả, được gọi là những Câu ví. Chẳng hạn:<br>
<center><i>Lạnh như tiền<br>
Thẳng như ruột ngựa<br>
Chắc như đinh đóng cột<br>
Dốt đặc cán mai<br>
Lúng túng như thợ vụng mất kim...</i></center></li>
</ul>
<li> Nguồn gốc của tục ngữ:</li>
<ul>
<li>Phần lớn các tục ngữ nảy sinh trong đời sống hàng ngày. Ban đầu, có khi chỉ là một câu nói thường nhưng nhờ có ý nghĩa xác đáng, lời lẽ cô đọng, dễ nhớ, được người khác thích thú, nhắc đi nhắc lại. Dần dần, câu nói được trau chuốt và phổ biến rộng hơn.</li>
<li>Có những câu vốn là thơ ca có tác giả nhưng nhờ ý đúng, lời hay, được nhiều người lưu tâm một cách đặc biệt rồi tách riêng để truyền tụng. Những câu như <i>Thương người như thể thương thân</i> trong Gia huấn ca (tương truyền của Nguyễn Trãi), <i>Khi nên trời cũng chiều người</i>, hay <i>Chữ "tài" liền với chữ "tai" một vần</i> trong Truyện Kiều của Nguyễn Du... có thể xếp vào loại này.</li>
<li>Có những câu tục ngữ được dịch từ ngạn ngữ nước ngoài như:<br>
<center><i>Ở hiền gặp lành</i> (Tích thiện phùng thiện - Trung hoa</center><br>
<center><i>Có công mài sắt, có ngày nên kim</i> (Ma chử thành châm - Trung hoa)</center><br>
<center><i>Lửa cháy đổ dầu thêm</i> (Hỏa thượng thiêm du - Trung hoa)</center><br>
<center><i>Thời giờ là tiền bạc</i> (Time is money - Anh)</center><br>
<center><i>Muốn là được</i> (Vouloir, c'est pouvoir - Pháp)</center>
</ul>
<li>Hình thức của tục ngữ:<br>
Trong tục ngữ có những câu:</li>
<ul>
<li>Không vần, chỉ có ý đối:</li>
<center><i>Giơ cao, đánh sẽ<br>
Ở bầu thì tròn, ở ống thì dài<br>
No nên bụt, đói ra ma</i></center><br>
<li>Không vần, không đối, chỉ cốt ý đúng, lời gọn:</li>
<center><i>Mật ngọt chết ruồi<br>
Ăn quả nhớ kẻ trồng cây</i></center><br>
<li>Nhưng phần lớn tục ngữ là những câu có vần, thường là vần lưng (yêu vận):<br>
<center><i>Ăn cây nào rào cây ấy<br>
Phép vua thua lệ làng<br>
Con có cha như nhà có nóc<br>
Một giọt máu đào hơn ao nước lã<br>
Cơn đằng đông vừa trông vừa chạy</i></center><br>
Đôi khi có những câu thêm cả vần chân (cước vận):<br>
<center><i>Khôn cho người rái,<br>
Dại cho người thương,<br>
Dở dở ương ương,<br>
Tổ cho người ghét.</i></center><br>
</ul>
</ol>
<h4>CA-DAO</h4>
<ol>
<li>Định nghĩa và biệt loại:</li>
<p>Ca dao (ca: bài hát thành chương khúc; dao: bài hát ngắn, không thành chương khúc) là những câu hát theo giọng điệu tự nhiên lưu hành trong dân gian, thường diễn tả ý nghĩ, tình cảm, nếp sinh hoạt của đại chúng bình dân. Ca dao còn được gọi là phong dao ("phong" là phong tục). Người xưa cho rằng qua ca dao có thể nhận biết phong tục tốt, xấu của một xứ, một vùng.</p>
<p>Một biệt loại khá quan trọng của ca dao là đồng dao ("đồng": trẻ con). Đồng dao là những bài hát dành cho trẻ con, toàn bài nhiều khi chỉ là một số câu có vần ghép lại với nhau, không có ý nghĩa rõ rệt. Tuy nhiên, đồng dao có thể giúp trẻ học một số danh từ về các vật thường gặp. Chẳng hạn:<br>
<center><i>Dung dăng dung dẻ<br>
Dắt trẻ đi chơi<br>
Đến cửa nhà trời<br>
Lạy cậu lạy mợ<br>
Cho cháu về quê<br>
Cho dê đi học<br>
Cho cóc ở nhà<br>
Cho gà bới bếp...</i></center><br>
hay:<br>
<center><i>Cái bống đi chợ cầu Canh<br>
Cái tôm đi trước, củ hành đi sau<br>
Con cua lật đật theo hầu<br>
Cái chày rơi xuống vỡ đầu con cua.</i></center></p>
<p>Một số biệt loại nữa của ca dao là các bài hát ru em, các bài vè, và các câu đố.</p>
<p>Vè là một loại ca dao có tính cách thời sự và địa phương, làm ra nhân một việc xảy ra tại địa phương khiến dư luận xôn xao. Vè thường nhằm mục đích chỉ trích, chế giễu.</p>
<p>Không có ranh giới rõ rệt giữa ca dao và dân ca. Có thể coi ca dao là phần lời thơ của các bài dân ca.<br>
Ca dao khác tục ngữ ở chỗ - theo định nghĩa - ca dao có thể hát lên được (tục ngữ: câu nói; ca dao: câu hát). Trong ca dao, vần điệu rõ rệt và âm hưởng êm ái hơn. Nói chung, câu ca dao dài hơn câu tục ngữ, và thường có nhiều câu hợp lại thành bài.<br>
Xét theo nội dung, tục ngữ thường là những nhận xét thuộc phạm vi lý trí trong khi ca dao là tiếng nói của tình cảm. Tuy nhiên, sự phân biệt này cũng không được chặt chẽ cho lắm: nhiều câu ca dao cũng thuộc phạm vi lý trí.</p>
<li>Cách kết cấu của ca dao:</li>
<p>Các học giả lớp trước thường theo Kinh Thi của Trung hoa mà phân biệt ba lối kết cấu (lập ý, dàn ý) của ca dao là: phú, tỉ, và hứng.</p>
<ul>
<li>Phú: là phô bày, mô tả, nói thẳng vào sự việc. Chẳng hạn:<br>
<center><i>Đường vô xứ Nghệ quanh quanh<br>
Non xanh nước biếc như tranh họa đồ<br>
Ai vô xứ Nghệ thì vô!</i></center><br>
hay:<br>
<center><i>Ngang lưng thì thắt bao vàng<br>
Đầu đội nón dấu, vai mang súng dài<br>
Một tay thì cắp hỏa mai<br>
Một tay cắp dáo quan sai xuống thuyền<br>
Thùng thùng trống đánh ngũ liên<br>
