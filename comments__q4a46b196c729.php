<li>Những truyện Trầu cau, Tấm Cám, Ba vị đầu rau, Túi ba gang (hai anh em và cây khế), Cây tre trăm đốt, Lưu Bình Dương Lễ, Cái cân thủy ngân, Giết chó dạy chồng... có thể xếp vào loại truyện luân lý.</li>
<li>Những chuyện về sự dối trá của thằng Cuội, Trạng Quỳnh lỡm chúa Trịnh, Trạng Lợn gặp may, cũng như những giai thoại về Ba Giai, Tú Xuất... có thể xếp vào loại truyện hài hước. </li>
<li>Thêm vào đó, dân ta còn có những truyện thần kỳ, thoát tục như Tú Uyên gặp tiên, Từ Thức lên tiên... (truyện Chử Đồng tử đã nhắc đến ở trên cũng có thể xếp vào loại này), và những truyện thần quái như Người lấy cóc, Sọ Dừa, Hồn Trương Ba, da hàng thịt, Ma xó... Chúng ta cũng có một số truyện ái tình thuần túy như Trưong Chi - Mỵ nương. 
Một số truyện cổ tích của dân tộc Việt (như các truyện Trăm trứng trăm trai, Tấm Cám, Thạch Sanh, Sọ Dừa...) cũng là truyện cổ tích của nhiều sắc dân thiểu số trên đất nước Việt Nam. Một số truyện Việt Nam cũng có thể tìm thấy trong kho tàng cổ tích của một vài dân tộc khác ở Đông Nam Á.
