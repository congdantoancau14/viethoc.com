<h4> Truyện cổ tích Việt Nam:</h4>
<ol>
<li>Hầu hết các dân tộc thiểu số trên đất nước Việt Nam đều có những thần thoại về nguồn gốc vũ trụ và nguồn gốc loài người. Chẳng hạn truyện ỏĐẻ đất, đẻ nướcõ của người Mường, các truyện về cơn đại hồng thủy vaụ quả bầu khổng lồ, nơi phát xuất những con người đầu tiên trên đất Việt cổ và các vùng lân cận, trong hầu hết các sưu tập cổ tích của người Thái, Lolo, Hmong, Bana, Raglai, Sedang, Vân kiều... 
Những chuyện Lạc Long quân trừ Ngư tinh, Hồ tinh, Mộc tinh; Thánh Tản viên (Sơn tinh) ngăn nước lụt... của người Việt có thể xếp vào loại thần thoại về sự chinh phục thiên nhiên và kỳ tích của anh hùng.</li>
<li> Những truyện "Cóc kiện trời", "Tại sao hổ có vằn", "Sự tích loài khỉ", "Sự tích con tu hú", "Sự tích con dã tràng"... trong kho tàng truyện cổ tích Việt Nam có thể xếp vào loại cổ tích về loài vật. </li>
