      <div class="PhorumReadBodyText"> <HTML>Kính thưa các bạn,<br />
<br />
Diễn đàn Việt Học từ trước tới nay là một diễn đàn mở rộng, chào đón tất cả mọi người, không phân biệt chính kiến, tôn giáo, tuổi tác v.v.. với hy vọng tất cả mọi người có quan tâm đến văn hóa Việt Nam sẽ có một nơi thảo luận nghiêm túc.<br />
<br />
Tuy nhiên, sau một thời gian vắng bóng vì bề bộn công việc, nay trở lại, chúng tôi thấy trong diễn đàn có một số bài viết thảo luận về các vấn đề tôn giáo, chính trị và tệ hơn nữa là đả kích cá nhân.  Chúng tôi rất buồn vì thấy vài thân hữu đã không tự chế và đã không giữ cho diễn đàn chung của chúng ta có một không khí nghiêm trang như ngày nào để thảo luận các vấn đề về Việt Học.<br />
<br />
Chúng tôi có quan hệ tốt với nhiều tôn giáo cũng như nhiều thân hữu có các chính kiến khác nhau ở cả trong và ngoài nước.  Vì chúng tôi muốn giữ tình thân hữu đó lâu dài và không muốn các sự khác biệt về tôn giáo và chính kiến ảnh hưởng đến chủ trương của chúng tôi là nghiên cứu Việt Học.<br />
<br />
Vì thế, mặc dù chúng tôi biết tôn giáo và chính trị cũng là những vấn đề của văn hóa Việt Nam, nhưng chúng tôi cũng nhận ra rằng các vấn đề này cũng thường là những vấn đề gây xung đột trong bất kỳ xã hội nào.  Đó là điều chúng tôi không muốn, vì thế cho dù rất tiếc, chúng tôi đã quyết định sẽ tránh các vấn đề này trong diễn đàn của chúng ta để bảo tồn điều quan trọng hơn, đó là tình thân hữu giữa chúng ta.<br />
<br />
Bắt đầu ngày hôm nay, 1 tháng 2 năm 2004, chúng tôi sẽ dò lại tất cả các bài đã viết và sẽ xóa bỏ tất cả những bài viết nào có nội dung chính trị, tôn giáo cũng như các bài viết nào có nội dung đả kích cá nhân, có lối viết thiếu tôn trọng độc giả.<br />
<br />
Mong các bạn hiểu và thông cảm cho chúng tôi.<br />
