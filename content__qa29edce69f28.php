               <td class="type5" width="90%" valign="top"><span class="boldtext">Curriculum</span><br /><h4>Undergraduate studies</h4>
<ul>
<li>Freshman year</li>
<ul>
<li>History: Generalities on the history of Vietnam from ancient times to modern times</li>
<li>Geography: natural, human and economic </li>
<li>Vietnamese language course</li>
<li>Overview on literary schools</li>
<li>Formation, Potential and Role of the Vietnamese communities overseas.</li>
<li>Introduction to the history and culture of the asylum countries.</li>
</ul>
<li>Sophomore year</li>
<ul>
<li>History: From the Trinh and Nguyen power struggle period to modern times</li>
<li>Literature: Philosophy and influences of literary schools, literary works and representative authors.</li>
<li>Present situation in Vietnam and Vietnam with the trends of modern times</li>
<li>Overview on Oriental philosophy</li>
<li>Overview on Western philosophy</li>
<li>Overview on Sociology. The role of man in society.</li>
</ul>
</ul>
<h4>Bachelor's of Arts in Humanities and Sociology Program</h4>
<p><u>Prerequisites:</u> Completion of Freshman and Sophomore years</p>
<ul>
<li>Junior year: </li>
<ul>
<li>Philosophy and Civilization of Vietnam </li>
<li>Comparative philosophies</li>
<li>Basic differences between the Vietnamese and Chinese cultures</li>
<li>Community and school activities</li>
<li>Vietnamese spirit of life through history</li>
<li>National identity and acculturation</li>
</ul>
<li>Senior year: Options: Sino-Vietnamese Studies - Literature - History and Geography -Chinese and Nôm (demotic characters)</li>
</ul>
<h4>Bachelor's of Arts in Education Program</h4>
<p><u>Prerequisites:</u> completion of Freshman and Sophomore years.</p>
<ul>
<li>Junior year: </li>
<ul>
<li>Philosophy and Civilization of Vietnam.</li>
<li>Comparative philosophies</li>
<li>Basic differences between the Vietnamese and Chinese cultures</li>
<li>Community and school activities.</li>
<li>Vietnamese education and comparative educational systems.</li>
<li>Educational systems in asylum countries</li>
<li>Vietnamese education in the 21st century.</li>
</ul>
<li>Senior year: Options: Education - Organization - Management - Leadership -Top management</li>
</ul>
