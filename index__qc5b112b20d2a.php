<h3>Few words</h3>



<img src="px/user_pages/sach100.jpg" align="left">
The following rare or out-of-print books are collective works and contributions from the Internet community. These books are essential and valuable to Vietnamese studies, particularly in the Vietnam History academic topic. Thus, Viện Việt-Học collects and keeps these electronic copies here for your research and reference convenience.<br />
<br /><br />
As briefly mentioned earlier, these valuable books available for you today are not in any way a small effort. In fact, tens of thousands of Vietnamese text pages were meticulously retyped, and hundreds of pictures were carefully scanned by a handful of individuals. The intention of that tremendous effort is not to serve any commercial purpose, but for preservation of Vietnam's history and heritage; with that Viện Việt-Học would like to recognize and appreciate those individuals who have made this collection possible.<br />




