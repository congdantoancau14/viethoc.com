</LI>
<br /><br />
<LI>
<a href="/eholdings/sach/vstt.pdf" target="_parent">Việt Sử Toàn Thư</a><br>
Do sử gia Phạm Văn Sơn soạn thảo vào năm 1960, hội chuyên gia Việt Nam chuyển sang ấn bản điện tử vào năm 1996.<br><br>
<LI>
<a href="/eholdings/sach/qtcbty.pdf" target="_parent">Quốc Triều Chánh Biên Toát Yếu</a><br>
Do Quốc Sử Quán Triều Nguyễn soạn thảo vào khoảng đầu thế kỷ 20. Nhóm Nghiên Cứu Sử Địa dịch sang chữ Quốc Ngữ vào năm 1972. Nhóm bạn Lê Bắc, Doãn Vượng, Công Đệ chuyển sang ấn bản điện tử năm 2001.<br><br>
<LI>
<a href="/eholdings/sach/kdvstgcm.pdf" target="_parent"><br />
Khâm Định Việt Sử Thông Giám Cương Mục</a><br>
Do Quốc Sử Quán Triều Nguyễn soạn thảo khoảng năm 1856-1881. Viện Sử học dịch sang chữ Quốc Ngữ vào năm 1960. Nhóm bạn Lê Bắc, Công Đệ, Ngọc Thủy, Tuyết Mai, Thanh Quyên chuyển sang ấn bản điện tử năm 2001.<br><br>
<LI>
<a href="/eholdings/sach/vsta.pdf" target="_parent">Việt Sử Tiêu Án</a><br>
Do Ngô Thời Sỹ soạn thảo vào năm 1775. Hội Việt Nam Nghiên Cứu Liên Lạc Văn Hóa Á Châu dịch sang chữ Quốc Ngữ vào năm 1960. Nhóm bạn Lê Bắc, Doãn Vượng, Công Đệ chuyển sang ấn bản điện tử năm 2001.<br><br>
<LI>
<a href="/eholdings/sach/dvts.pdf" target="_parent">Đại Việt Thông Sử</a><br>Do Lê Quý Đôn soạn thảo vào năm 1759. Lê Mạnh Liêu dịch sang chữ Quốc Ngữ vào năm 1973. Nhóm bạn Lê Bắc, Công Đệ chuyển sang ấn bản điện tử năm 2001.<br><br>
<LI>
<a href="/eholdings/sach/dvsktt.pdf" target="_parent">Đại Việt Sử Ký Toàn Thư</a><br>
Do nhiều sử gia nhà Trần và nhà Lê soạn thảo ra. Năm 1993, nhà XBKHXH ấn hành bản chữ Quốc Ngữ, dịch từ bản in năm Chính Hòa thứ 18 (1697). Nhóm bạn Lê Bắc, Công Đệ, Ngọc Thủy, Tuyết Mai, Hồng Ty và Nguyễn Quang Trung chuyển sang ấn bản điện tử năm 1999.<br><br>
<LI>
<a href="/eholdings/sach/lstl.pdf" target="_parent">Lam Sơn Thực Lục</a><br>
Do Nguyễn Trãi soạn thảo, Lê Lợi đề tựa vào thế kỷ 15. Mạc Bảo Thần dịch sang chữ Quốc Ngữ vào năm 1944. Nhóm bạn Lê Bắc, Công Đệ, Tuyết Mai và Doãn Vượng chuyển sang ấn bản điện tử năm 2001.<br><br>
