<h3>Mục đích</h3>



<p><img src="/px/user_pages/vvh_nom.jpg" align="right">Do hoàn-cảnh lịch-sử, dân-tộc Việt-nam hiện nay không chỉ sinh sống trong lãnh-thổ Việt-nam mà đã trải rộng khắp thế-giới. Ðể các thế-hệ trẻ của cộng-đồng Việt-nam tại hải-ngoại không xa lìa gốc rễ văn-hoá - vốn là sức mạnh tinh-thần của dân-tộc - việc nghiên-cứu và giảng dạy ngôn-ngữ, văn-học, văn-hoá, lịch-sử, địa-lý Việt-nam tại hải-ngoại đã trở nên vô cùng khẩn-thiết.</p>
<br />
<p>Với chức-năng nghiên-cứu, quảng-bá và giảng dạy, Viện Việt-học hướng đến các mục-tiêu sau đây:</p>
<ul>
<li>Tạo sự cảm-thông và góp phần duy-trì mối liên-hệ mật-thiết giữa người Việt đang sống tại khắp nơi trên thế-giới; </li>
<li>Phân-tích một cách nghiêm-túc ưu, nhược điểm của văn-hóa Việt-nam. Thẩm-định một cách khách-quan địa-vị cùng vai-trò của văn-hoá ấy trong toàn thể văn-hoá nhân-loại; </li>
<li>Tìm cách bồi-dưỡng và phát-huy những nét đẹp, đáng trân-trọng gìn-giữ trong nếp sống tinh-thần của người Việt-nam; </li>
<li>Góp ý một cách cụ-thể, sáng-tạo và hướng-thượng trước nhu-cầu thích-nghi một cách hài-hoà văn-hoá Việt-nam và văn-hoá địa-phương cũng như thế-giới.</li>
</ul><br />




<h3>About Us</h3>



<p><img src="/px/user_pages/vvh_nom.jpg" align="left">The Institute of Vietnamese Studies is a private, non-profit interdisciplinary research institution. The Institute is established to exchange information on, and to promote public awareness of Vietnamese culture, history and literature among historians, scholars, students and the public. The Institute of Vietnamese Studies offers high quality education programs, as well as correspondence courses. Besides these programs and courses, which respond to learners' needs, the Institute also sponsors many projects related to Vietnamese studies. </p>
<br />
<p>The Institute's activities currently include: </p>
<ul>
<li>Vietnamese courses conducted by the Institute's faculty members. </li>
<li>A public web-site where users can exchange news, information, publications, and discussions about Vietnam or Vietnamese culture, language, history, geography, and literature. </li>
<li>Conferences, seminars, and lectures conducted by the Institute's faculty members and distinguished guest speakers. </li>
<li>A research library which collects books, magazines, videos and manuscripts relating to the earliest period of Vietnam's history. The collection covers the establishment of the country, the Chinese and French colonial periods, the Vietnam war and life of the Vietnamese refugees. </li>
</ul><br />




