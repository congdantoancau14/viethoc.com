                <p><h4>ASSIST SCHOLARS - HOST SEMINARS - PROVIDE LECTURES</h4>
<p>Through diverse programs,  the Institute of Vietnamese Studies hopes to draw together the Vietnamese  overseas to revitalize the Vietnamese  heritage, as well as to promote and to encourage awareness of Vietnamese culture, history and literature among historians, scholars, students and the public .</p>
<p>Functions of the Institute include:
<ul>
<li>Assisting individual scholars or teams of  scholars conducting research about Vietnam</li>
<li>Providing correspondence and classroom courses</li>
<li>Hosting seminars for teachers of secondary educational institutions. 
