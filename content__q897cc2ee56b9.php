              <p><h4>Vietnam Research Library: BOOKS AND MANUSCRIPTS COLLECTION</h4>
<p>The Vietnam Research Library is located on  the Institute of Vietnamese Studies Southern  California campus. Established in February 2000, the library provides access to materials about Vietnam. Its regular patrons include teachers, researchers, students and administrators at other teaching institutions. </p>
<p>In the near future, the library plans to extend its services by cooperating with other Vietnam Studies libraries in United States as well as around the world. </p>
<p>The library is collecting  books and manuscripts relating to the earliest period of Vietnam's history. The  collection's range extends from the establishment of the country, through the Chinese and French  colonial periods, to Vietnam's recent wars and  the modern lives of Vietnamese refugees. </p>
